/**
 * Icons — builds an SVG sprite of the icons listed in tokens/icons.json from
 * the Iconoir package (node_modules/iconoir). Pages inline the sprite once
 * and reference icons with <use href="#icon-name">. (Pointing <use> at the
 * external file also works, but costs ~12ms per icon in Chrome: the Icons
 * page took 11s to paint that way, 0.1s inlined.)
 *
 * Shared by scripts/build-tokens.mjs (sprite + llms.txt) and the Icons page.
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Symbol ids are prefixed so icon names ("menu", "search", "home") can't
 * collide with other ids once the sprite is inlined into a page.
 */
export const ICON_ID_PREFIX = "icon-";

/** Unique icon names in catalog order. */
export function iconNames(catalog) {
  const names = catalog.categories.flatMap((c) => c.groups.flatMap((g) => g.icons));
  return [...new Set(names)];
}

/**
 * Iconoir files look like
 *   <svg width="24" height="24" stroke-width="1.5" viewBox="0 0 24 24" fill="none" …>…</svg>
 * Each becomes a <symbol> whose root attributes (stroke width, fill) move to
 * a wrapping <g>, so they still apply inside <use>.
 */
function toSymbol(name, svg) {
  const open = svg.match(/<svg\b([^>]*)>/);
  if (!open) throw new Error(`icons: ${name}.svg has no <svg> root`);
  const attr = (key) => open[1].match(new RegExp(`\\b${key}="([^"]*)"`))?.[1];
  const inner = svg
    .slice(open.index + open[0].length, svg.lastIndexOf("</svg>"))
    .trim()
    .replace(/\s*\n\s*/g, "");
  const groupAttrs = [
    attr("fill") && `fill="${attr("fill")}"`,
    attr("stroke-width") && `stroke-width="${attr("stroke-width")}"`,
  ]
    .filter(Boolean)
    .join(" ");
  return `<symbol id="${ICON_ID_PREFIX}${name}" viewBox="${attr("viewBox") ?? "0 0 24 24"}"><g ${groupAttrs}>${inner}</g></symbol>`;
}

export function buildIconSprite(catalog, root) {
  const dir = join(root, "node_modules", catalog.library.package, "icons", catalog.library.style);
  const missing = [];
  const symbols = iconNames(catalog).map((name) => {
    try {
      return toSymbol(name, readFileSync(join(dir, `${name}.svg`), "utf8"));
    } catch (error) {
      if (error.code === "ENOENT") missing.push(name);
      else throw error;
      return "";
    }
  });
  if (missing.length) {
    throw new Error(`icons: not in ${catalog.library.package}/${catalog.library.style}: ${missing.join(", ")}`);
  }
  const version = JSON.parse(readFileSync(join(root, "node_modules", catalog.library.package, "package.json"), "utf8")).version;
  return `<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" style="position:absolute;width:0;height:0;overflow:hidden"><!-- GENERATED by scripts/build-tokens.mjs from tokens/icons.json and ${catalog.library.package}@${version} (${catalog.library.license}). Do not edit by hand. -->${symbols.join("")}</svg>\n`;
}
