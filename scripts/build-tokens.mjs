#!/usr/bin/env node
/**
 * Generates CSS custom properties from the Figma variables export.
 *
 *   Source: tokens/figma-variables.json  (exported from "Foundation – UI 2")
 *   Output: src/styles/tokens/{color,typography,sizing}.css
 *
 * Run with `npm run tokens`. Never edit the generated CSS by hand —
 * change the variables in Figma, re-export, and re-run this script.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { PRIMITIVE_PREFIX as PRIMITIVE, SEMANTIC_PREFIX as SEMANTIC, colorName } from "./token-names.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = JSON.parse(readFileSync(join(root, "tokens/figma-variables.json"), "utf8"));
const outDir = join(root, "src/styles/tokens");

const HEADER = (from) =>
  `/*\n * GENERATED by scripts/build-tokens.mjs from tokens/figma-variables.json\n * (Figma collection: ${from}). Do not edit by hand.\n */\n`;

// ---------- naming ----------------------------------------------------------

/** font/weight/strong → --font-weight-strong, heading/large/fontSize → --heading-large-font-size */
function kebab(figmaName) {
  return (
    "--" +
    figmaName
      .split("/")
      .map((p) => p.replace(/([a-z])([A-Z])/g, "$1-$2").toLowerCase())
      .join("-")
  );
}

function assertUnique(names, label) {
  const seen = new Map();
  for (const [figma, css] of names) {
    if (seen.has(css)) throw new Error(`${label}: ${figma} and ${seen.get(css)} both map to ${css}`);
    seen.set(css, figma);
  }
}

// ---------- colors ----------------------------------------------------------

function buildColors({ modes, vars }) {
  const entries = Object.entries(vars);
  assertUnique(entries.map(([n]) => [n, colorName(n)]), "Colors");

  const light = modes.indexOf("Light");
  const dark = modes.indexOf("Dark");
  const value = (v) => (typeof v === "object" && v.alias ? `var(${colorName(v.alias)})` : v);

  const primitives = entries.filter(([n]) => n.startsWith(PRIMITIVE));
  const semantics = entries.filter(([n]) => n.startsWith(SEMANTIC));

  const decl = (list, mode) => list.map(([n, vals]) => `  ${colorName(n)}: ${value(vals[mode])};`).join("\n");

  // Dark block: only primitives whose value changes, but *every* semantic
  // token, so they re-resolve against the dark primitives inside a
  // [data-theme="dark"] subtree.
  const darkPrimitives = primitives.filter(([, vals]) => vals[light] !== vals[dark]);

  return (
    HEADER("Colors") +
    `
/* Light (default) */
:root,
[data-theme="light"] {
  color-scheme: light;

  /* Primitives */
${decl(primitives, light)}

  /* Semantic */
${decl(semantics, light)}
}

/* Dark */
[data-theme="dark"] {
  color-scheme: dark;

  /* Primitives that differ from light */
${decl(darkPrimitives, dark)}

  /* Semantic */
${decl(semantics, dark)}
}
`
  );
}

// ---------- typography -----------------------------------------------------

function buildTypography({ vars }) {
  const raw = Object.fromEntries(Object.entries(vars).map(([n, [v]]) => [n, v]));
  const ref = (v) => (typeof v === "object" && v.alias ? `var(${kebab(v.alias)})` : v);

  const fontFallbacks = {
    "Roboto Mono": `"Roboto Mono", ui-monospace, SFMono-Regular, Menlo, monospace`,
    Inter: `"Inter", system-ui, -apple-system, "Segoe UI", sans-serif`,
  };

  const lines = [];
  const styles = new Map(); // "heading/large" → { fontSize, ... }

  for (const [name, v] of Object.entries(raw)) {
    const css = kebab(name);
    const prop = name.split("/").at(-1);
    if (name.startsWith("font/family/")) lines.push(`  ${css}: ${fontFallbacks[v] ?? `"${v}"`};`);
    else if (name.startsWith("font/weight/")) lines.push(`  ${css}: ${v};`);
    else {
      const style = name.split("/").slice(0, -1).join("/");
      if (!styles.has(style)) styles.set(style, {});
      styles.get(style)[prop] = v;
      let out;
      if (prop === "fontSize" || prop === "lineHeight") out = `${v}px`;
      // Figma letter spacing is a percentage of the font size.
      else if (prop === "letterSpacing") out = `${+(v / 100).toFixed(5)}em`;
      else out = ref(v);
      lines.push(`  ${css}: ${out};`);
    }
  }

  // One utility class per Figma text style. "…/strong" styles also get a
  // regular-weight sibling (e.g. .text-body-large) using font/weight/default,
  // matching the "body/large/regular" text style used in the layouts.
  const classes = [];
  for (const style of styles.keys()) {
    const p = kebab(style);
    const cls = p.slice(2);
    const rule = (selector, weight) =>
      `.text-${selector} {\n` +
      `  font-family: var(${p}-font-family);\n` +
      `  font-size: var(${p}-font-size);\n` +
      `  line-height: var(${p}-line-height);\n` +
      `  font-weight: ${weight};\n` +
      `  letter-spacing: var(${p}-letter-spacing);\n}`;
    classes.push(rule(cls, `var(${p}-font-weight)`));
    if (style.endsWith("/strong")) classes.push(rule(cls.replace(/-strong$/, ""), "var(--font-weight-default)"));
  }

  return HEADER("Typography") + `\n:root {\n${lines.join("\n")}\n}\n\n${classes.join("\n\n")}\n`;
}

// ---------- sizing ---------------------------------------------------------

function buildSizing({ vars }) {
  const name = (n) =>
    n.startsWith("Spacers/spacer-") ? `--space-${n.split("-").at(-1)}` : `--${n.split("/").at(-1)}`;
  const entries = Object.entries(vars).sort(([a], [b]) => a.localeCompare(b, "en", { numeric: true }));
  assertUnique(entries.map(([n]) => [n, name(n)]), "Sizing");
  const lines = entries.map(([n, [v]]) => `  ${name(n)}: ${v}px;`);
  return HEADER("Sizing") + `\n:root {\n${lines.join("\n")}\n}\n`;
}

// ---------- write ----------------------------------------------------------

const files = {
  "color.css": buildColors(source.Colors),
  "typography.css": buildTypography(source.Typography),
  "sizing.css": buildSizing(source.Sizing),
};

for (const [file, css] of Object.entries(files)) {
  writeFileSync(join(outDir, file), css);
  console.log(`wrote src/styles/tokens/${file}`);
}
