#!/usr/bin/env node
/**
 * Generates CSS custom properties from the Figma variables export, plus
 * machine-readable files so AI agents and tools can pick up the styles.
 *
 *   Source: tokens/figma-variables.json  (exported from "Foundation – UI 2")
 *           tokens/typography-rules.json (when to use each text style)
 *           tokens/button-rules.json     (when to use each button variant)
 *           tokens/icons.json            (icon catalog, Iconoir names)
 *   Output: src/styles/tokens/{color,typography,sizing}.css
 *           tokens/color-rules.json      (when to use each color token)
 *   Output: …and for AI agents / tools:
 *           public/tokens/typography.json  (W3C design tokens + usage rules)
 *           public/tokens/colors.json      (primitives + semantic, light/dark, usage rules)
 *           public/llms.txt                (LLM-readable summary, served at /llms.txt)
 *           public/icons/iconoir.svg       (sprite of the catalog's Iconoir icons)
 *
 * Run with `npm run tokens`. Never edit the generated CSS by hand —
 * change the variables in Figma, re-export, and re-run this script.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { PRIMITIVE_PREFIX as PRIMITIVE, SEMANTIC_PREFIX as SEMANTIC, colorName, semanticName } from "./token-names.mjs";
import { kebab, typographyStyles } from "./typography.mjs";
import { colorTokens } from "./colors.mjs";
import { buildIconSprite, iconNames } from "./icons.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = JSON.parse(readFileSync(join(root, "tokens/figma-variables.json"), "utf8"));
const typographyRules = JSON.parse(readFileSync(join(root, "tokens/typography-rules.json"), "utf8"));
const colorRules = JSON.parse(readFileSync(join(root, "tokens/color-rules.json"), "utf8"));
const buttonRules = JSON.parse(readFileSync(join(root, "tokens/button-rules.json"), "utf8"));
const icons = JSON.parse(readFileSync(join(root, "tokens/icons.json"), "utf8"));

const HEADER = (from) =>
  `/*\n * GENERATED by scripts/build-tokens.mjs from tokens/figma-variables.json\n * (Figma collection: ${from}). Do not edit by hand.\n */\n`;

// ---------- naming ----------------------------------------------------------

function assertUnique(names, label) {
  const seen = new Map();
  for (const [figma, css] of names) {
    if (seen.has(css)) throw new Error(`${label}: ${figma} and ${seen.get(css)} both map to ${css}`);
    seen.set(css, figma);
  }
}

// ---------- colors ----------------------------------------------------------

function buildColors({ modes, vars }) {
  const entries = Object.entries(vars);
  assertUnique(entries.map(([n]) => [n, colorName(n)]), "Colors");

  const light = modes.indexOf("Light");
  const dark = modes.indexOf("Dark");
  const value = (v) => (typeof v === "object" && v.alias ? `var(${colorName(v.alias)})` : v);

  const primitives = entries.filter(([n]) => n.startsWith(PRIMITIVE));
  const semantics = entries.filter(([n]) => n.startsWith(SEMANTIC));

  const decl = (list, mode) => list.map(([n, vals]) => `  ${colorName(n)}: ${value(vals[mode])};`).join("\n");

  // Dark block: only primitives whose value changes, but *every* semantic
  // token, so they re-resolve against the dark primitives inside a
  // [data-theme="dark"] subtree.
  const darkPrimitives = primitives.filter(([, vals]) => vals[light] !== vals[dark]);

  return (
    HEADER("Colors") +
    `
/* Light (default) */
:root,
[data-theme="light"] {
  color-scheme: light;

  /* Primitives */
${decl(primitives, light)}

  /* Semantic */
${decl(semantics, light)}
}

/* Dark */
[data-theme="dark"] {
  color-scheme: dark;

  /* Primitives that differ from light */
${decl(darkPrimitives, dark)}

  /* Semantic */
${decl(semantics, dark)}
}
`
  );
}

// ---------- typography -----------------------------------------------------

function buildTypography({ vars }) {
  const raw = Object.fromEntries(Object.entries(vars).map(([n, [v]]) => [n, v]));
  const ref = (v) => (typeof v === "object" && v.alias ? `var(${kebab(v.alias)})` : v);

  const fontFallbacks = {
    "Roboto Mono": `"Roboto Mono", ui-monospace, SFMono-Regular, Menlo, monospace`,
    Inter: `"Inter", system-ui, -apple-system, "Segoe UI", sans-serif`,
  };

  const lines = [];
  const styles = new Map(); // "heading/large" → { fontSize, ... }

  for (const [name, v] of Object.entries(raw)) {
    const css = kebab(name);
    const prop = name.split("/").at(-1);
    if (name.startsWith("font/family/")) lines.push(`  ${css}: ${fontFallbacks[v] ?? `"${v}"`};`);
    else if (name.startsWith("font/weight/")) lines.push(`  ${css}: ${v};`);
    else {
      const style = name.split("/").slice(0, -1).join("/");
      if (!styles.has(style)) styles.set(style, {});
      styles.get(style)[prop] = v;
      let out;
      if (prop === "fontSize" || prop === "lineHeight") out = `${v}px`;
      // Figma letter spacing is a percentage of the font size.
      else if (prop === "letterSpacing") out = `${+(v / 100).toFixed(5)}em`;
      else out = ref(v);
      lines.push(`  ${css}: ${out};`);
    }
  }

  // One utility class per Figma text style. "…/strong" styles also get a
  // regular-weight sibling (e.g. .text-body-large) using font/weight/default,
  // matching the "body/large/regular" text style used in the layouts.
  const classes = [];
  for (const style of styles.keys()) {
    const p = kebab(style);
    const cls = p.slice(2);
    const rule = (selector, weight) =>
      `.text-${selector} {\n` +
      `  font-family: var(${p}-font-family);\n` +
      `  font-size: var(${p}-font-size);\n` +
      `  line-height: var(${p}-line-height);\n` +
      `  font-weight: ${weight};\n` +
      `  letter-spacing: var(${p}-letter-spacing);\n}`;
    classes.push(rule(cls, `var(${p}-font-weight)`));
    if (style.endsWith("/strong")) classes.push(rule(cls.replace(/-strong$/, ""), "var(--font-weight-default)"));
  }

  return HEADER("Typography") + `\n:root {\n${lines.join("\n")}\n}\n\n${classes.join("\n\n")}\n`;
}

// ---------- sizing ---------------------------------------------------------

function buildSizing({ vars }) {
  const name = (n) =>
    n.startsWith("Spacers/spacer-") ? `--space-${n.split("-").at(-1)}` : `--${n.split("/").at(-1)}`;
  const entries = Object.entries(vars).sort(([a], [b]) => a.localeCompare(b, "en", { numeric: true }));
  assertUnique(entries.map(([n]) => [n, name(n)]), "Sizing");
  const lines = entries.map(([n, [v]]) => `  ${name(n)}: ${v}px;`);
  return HEADER("Sizing") + `\n:root {\n${lines.join("\n")}\n}\n`;
}

// ---------- agent-readable outputs -------------------------------------------

/** W3C Design Tokens (DTCG) typography tokens, nested by Figma style name. */
function buildTypographyJson() {
  const styles = typographyStyles(source, typographyRules);
  const tree = {
    $description:
      "A/W Design System typography. Generated from Figma (Foundation – UI 2) by scripts/build-tokens.mjs. " +
      "Apply a style with its CSS class (see $extensions['design.aw']) or its CSS variables.",
    $extensions: { "design.aw": { rules: typographyRules.rules } },
  };
  for (const s of styles) {
    let node = tree;
    for (const part of s.figmaStyle.split("/")) node = node[part] ??= {};
    Object.assign(node, {
      $type: "typography",
      $description: s.usage,
      $value: {
        fontFamily: s.values.fontFamily,
        fontSize: `${s.values.fontSize}px`,
        fontWeight: s.values.fontWeight,
        lineHeight: `${s.values.lineHeight}px`,
        letterSpacing: s.values.letterSpacing,
      },
      $extensions: {
        "design.aw": { label: s.label, cssClass: `.${s.className}`, cssVariables: s.cssVariables, figmaStyle: s.figmaStyle },
      },
    });
  }
  return JSON.stringify(tree, null, 2) + "\n";
}

/**
 * W3C Design Tokens (DTCG) colors. $value is the light-mode value (semantic
 * tokens are aliases to primitives); $extensions["design.aw"].modes holds
 * light and dark, since DTCG has no standard for modes yet.
 */
function buildColorsJson() {
  const { primitives, semantic } = colorTokens(source, colorRules);
  const ref = (alias) => `{primitive.${alias.replaceAll("/", ".")}}`;
  const tree = {
    $description:
      "A/W Design System colors. Generated from Figma (Foundation – UI 2) by scripts/build-tokens.mjs. " +
      "$value is light mode; see $extensions['design.aw'].modes for light and dark. Use semantic tokens in components.",
    $extensions: {
      "design.aw": {
        rules: colorRules.rules,
        modes: ["light", "dark"],
        defaultMode: "light",
        darkModeSelector: '[data-theme="dark"]',
      },
    },
    primitive: { $description: colorRules.primitives.description },
    semantic: { $description: "Purpose-named tokens that point to primitives per mode. Use these in components." },
  };
  const place = (root, path, token) => {
    let node = root;
    for (const part of path) node = node[part] ??= {};
    Object.assign(node, token);
  };

  for (const p of primitives) {
    tree.primitive[p.family] ??= p.description ? { $description: p.description } : {};
    place(tree.primitive, p.path, {
      $type: "color",
      $value: p.values.light,
      $extensions: {
        "design.aw": { cssVariable: p.cssVariable, figmaVariable: p.figmaVariable, modes: p.values },
      },
    });
  }
  for (const t of semantic) {
    place(tree.semantic, t.path, {
      $type: "color",
      $value: t.aliases.light ? ref(t.aliases.light) : t.values.light,
      $description: t.description,
      $extensions: {
        "design.aw": {
          cssVariable: t.cssVariable,
          figmaVariable: t.figmaVariable,
          modes: {
            light: t.aliases.light ? ref(t.aliases.light) : t.values.light,
            dark: t.aliases.dark ? ref(t.aliases.dark) : t.values.dark,
          },
          resolved: t.values,
        },
      },
    });
  }
  return JSON.stringify(tree, null, 2) + "\n";
}

/** llms.txt — a plain-markdown overview for LLMs (https://llmstxt.org). */
function buildLlmsTxt() {
  const styles = typographyStyles(source, typographyRules);
  const { primitives, semantic } = colorTokens(source, colorRules);

  const typeRows = styles.map(
    (s) =>
      `| \`.${s.className}\` | ${s.figmaStyle} | ${s.values.fontSize}/${s.values.lineHeight} | ${s.values.fontWeight} | ${s.values.letterSpacing} | ${s.usage} |`,
  );
  const semanticRows = semantic.map(
    (t) =>
      `| \`${t.cssVariable}\` | ${t.aliases.light ?? t.values.light} (${t.values.light}) | ${t.aliases.dark ?? t.values.dark} (${t.values.dark}) | ${t.description} |`,
  );
  const families = [...new Set(primitives.map((p) => p.family))];
  const primitiveRows = families.map((f) => {
    const steps = primitives.filter((p) => p.family === f);
    const shifts = steps.some((p) => p.values.light !== p.values.dark);
    const list = steps.map((p) => `${p.step} ${p.values.light}${shifts ? ` / ${p.values.dark}` : ""}`).join(", ");
    return `| ${f} | \`--color-${f}-<step>\` | ${list} | ${colorRules.primitives.families[f] ?? ""} |`;
  });

  return `# A/W Design System

> Design tokens and documentation for the A/W design system, generated from Figma (Foundation – UI 2). Use the CSS classes and custom properties below instead of hard-coded values.

This file is generated by \`npm run tokens\` (scripts/build-tokens.mjs). Do not edit by hand.

## Typography

${typographyRules.intro}

Font: ${styles[0].values.fontFamily} (variable weights). Rules:

${typographyRules.rules.map((r) => `- ${r}`).join("\n")}

| Class | Figma style | Size/Line height (px) | Weight | Letter spacing | When to use |
| --- | --- | --- | --- | --- | --- |
${typeRows.join("\n")}

Each class sets font-family, font-size, line-height, font-weight and letter-spacing. The same values are available as CSS variables, e.g. \`var(--heading-large-font-size)\`.

## Color

Rules:

${colorRules.rules.map((r) => `- ${r}`).join("\n")}

### Semantic tokens

Use these in components. Values are \`primitive (hex)\`; dark mode applies inside \`[data-theme="dark"]\`.

| CSS variable | Light | Dark | When to use |
| --- | --- | --- | --- |
${semanticRows.join("\n")}

### Primitives

${colorRules.primitives.description} Values are light (and dark, where they differ).

| Family | CSS variable | Steps | Notes |
| --- | --- | --- | --- |
${primitiveRows.join("\n")}

## Spacing and radius

${Object.entries(source.Sizing.vars)
  .map(([n, [v]]) => `\`${n.startsWith("Spacers/spacer-") ? `--space-${n.split("-").at(-1)}` : `--${n.split("/").at(-1)}`}\`: ${v}px`)
  .sort((a, b) => a.localeCompare(b, "en", { numeric: true }))
  .join(" · ")}

## Icons

${icons.intro}

Library: [${icons.library.name}](${icons.library.url}) (${icons.library.license}), ${icons.library.style} style — ${iconNames(icons).length} icons, in one sprite, \`/icons/iconoir.svg\` (symbol ids \`icon-<name>\`). Inline the sprite once per page, then use the Icon Shell: \`<svg class="icon icon--24" aria-hidden="true"><use href="#icon-bell"></use></svg>\` (styles: src/styles/components/icon.css).

| Size | Class | When to use |
| --- | --- | --- |
${icons.sizes.map((s) => `| ${s.size}px | \`.icon--${s.size}\`${s.size === 24 ? " (default)" : ""} | ${s.usage} |`).join("\n")}

Rules:

${icons.rules.map((r) => `- ${r}`).join("\n")}

### Icon names

${icons.categories
  .map((c) => `#### ${c.name}\n\n${c.groups.map((g) => `- ${g.name}: ${g.icons.join(", ")}`).join("\n")}`)
  .join("\n\n")}

## Components

### Button

${buttonRules.intro}

Markup: \`<button class="button button--<variant>" type="button">Label</button>\` (styles: src/styles/components/button.css). Hover, pressed, focus and disabled states are built in.

| Class | When to use |
| --- | --- |
${buttonRules.variants.map((v) => `| \`.button--${v.variant}\` | ${v.usage} |`).join("\n")}

Rules:

${buttonRules.rules.map((r) => `- ${r}`).join("\n")}

### Icon button

${buttonRules.iconButton.intro}

Markup: \`<button class="icon-button" type="button" aria-label="…"><svg class="icon" aria-hidden="true"><use href="#icon-bell"></use></svg></button>\` (styles: src/styles/components/icon-button.css).

| State | Look |
| --- | --- |
${buttonRules.iconButton.states.map((s) => `| ${s.label} | ${s.usage} |`).join("\n")}

Rules:

${buttonRules.iconButton.rules.map((r) => `- ${r}`).join("\n")}

## Files

- [Color tokens (W3C design tokens JSON: primitives + semantic, light/dark, usage rules)](tokens/colors.json)
- [Typography tokens (W3C design tokens JSON, with usage rules)](tokens/typography.json)
- [Figma variables export (source of truth)](https://github.com/adamw-studio/design-system-A-W/blob/main/tokens/figma-variables.json)
`;
}

// ---------- write ----------------------------------------------------------

const files = {
  "src/styles/tokens/color.css": buildColors(source.Colors),
  "src/styles/tokens/typography.css": buildTypography(source.Typography),
  "src/styles/tokens/sizing.css": buildSizing(source.Sizing),
  "public/tokens/typography.json": buildTypographyJson(),
  "public/tokens/colors.json": buildColorsJson(),
  "public/llms.txt": buildLlmsTxt(),
  "public/icons/iconoir.svg": buildIconSprite(icons, root),
};

mkdirSync(join(root, "public/tokens"), { recursive: true });
for (const [file, content] of Object.entries(files)) {
  writeFileSync(join(root, file), content);
  console.log(`wrote ${file}`);
}
